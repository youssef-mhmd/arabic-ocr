"""Download the training fonts listed in training/configs/fonts.yaml.

Usage:
    uv run python -m training.download_fonts

For each font family it:
1. reads the family's METADATA.pb from the Google Fonts repo,
2. refuses it unless the license is allowed and the font supports Arabic,
3. downloads the font files and license text into data/fonts/<dir>/,
4. records license, files, checksums, and charset coverage in training/fonts.json,
5. rewrites the fonts table in data/LICENSES.md.

Everything is pinned to the Google Fonts commit recorded in fonts.json, so re-running
gives the same files (use --update to move to the newest commit). Files that already
exist are not downloaded again.

    uv run python -m training.download_fonts --only notonaskharabic,vazirmatn   # just some
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
import urllib.error
import urllib.request
from pathlib import Path

import freetype
import numpy as np
import yaml

from arabic_ocr import charset
from training.render import render_line

ROOT = Path(__file__).resolve().parent.parent
CONFIG = ROOT / "training" / "configs" / "fonts.yaml"
MANIFEST = ROOT / "training" / "fonts.json"
FONTS_DIR = ROOT / "data" / "fonts"
LICENSES_MD = ROOT / "data" / "LICENSES.md"

LICENSE_DIRS = {"OFL": "ofl", "APACHE2": "apache", "UFL": "ufl"}
LICENSE_FILES = {"OFL": "OFL.txt", "APACHE2": "LICENSE.txt", "UFL": "UFL.txt"}
LICENSE_NAMES = {"OFL": "SIL Open Font License 1.1", "APACHE2": "Apache-2.0"}
USER_AGENT = "arabic-ocr-font-downloader"

TABLE_START = "<!-- fonts:start (generated by training/download_fonts.py) -->"
TABLE_END = "<!-- fonts:end -->"


def fetch(url: str) -> bytes:
    req = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
    with urllib.request.urlopen(req, timeout=60) as resp:
        return resp.read()


def resolve_commit(repo: str, ref: str) -> str:
    """Turn a branch name like "main" into a fixed commit id."""
    if re.fullmatch(r"[0-9a-f]{40}", ref):
        return ref
    data = json.loads(fetch(f"https://api.github.com/repos/{repo}/commits/{ref}"))
    return data["sha"]


def find_metadata(repo: str, commit: str, family_dir: str) -> tuple[str, str]:
    """Return (license folder, METADATA.pb text). Tries ofl/, apache/, ufl/."""
    for folder in LICENSE_DIRS.values():
        url = f"https://raw.githubusercontent.com/{repo}/{commit}/{folder}/{family_dir}/METADATA.pb"
        try:
            return folder, fetch(url).decode("utf-8")
        except urllib.error.HTTPError as err:
            if err.code != 404:
                raise
    raise FileNotFoundError(f"{family_dir}: not found in the Google Fonts repo")


def parse_metadata(text: str) -> dict:
    """Pull the few fields we need out of METADATA.pb (a simple text format)."""

    def field(name: str, block: str) -> list[str]:
        return re.findall(rf'^\s*{name}: "([^"]*)"', block, flags=re.MULTILINE)

    files = []
    for block in re.findall(r"^fonts \{(.*?)^\}", text, flags=re.MULTILINE | re.DOTALL):
        weight = re.search(r"^\s*weight: (\d+)", block, flags=re.MULTILINE)
        files.append(
            {
                "filename": field("filename", block)[0],
                "style": field("style", block)[0],
                "weight": int(weight.group(1)) if weight else 400,
            }
        )
    return {
        "family": field("name", text)[0],
        "designer": field("designer", text)[0] if field("designer", text) else "",
        "license": field("license", text)[0],
        "subsets": field("subsets", text),
        "files": files,
    }


def _shaped(font_path: Path, text: str) -> np.ndarray:
    """The digit exactly as training images draw it: through HarfBuzz shaping, after
    an Arabic word (fonts may swap digit shapes in Arabic context)."""
    return render_line(text, font_path, size_px=40, padding=0)


def lookalike_digits(font_path: Path, covered: set[str]) -> set[str]:
    """Digits that this font draws identically to a digit from another set.

    Examples found in our fonts: Zain Italic draws ٤ exactly like 4; Qahiri draws
    Arabic-Indic ٤ ٥ ٦ exactly like Persian ۴ ۵ ۶. An image of that would be labeled
    ٤ while showing 4 (or ۴), which teaches the model the wrong thing. We can't tell
    which shape is the "real" one, so both digits are treated as missing.

    Arabic-Indic and Persian 0-3 and 7-9 really are the same shapes, so only 4, 5 and
    6 are compared between those two sets.
    """
    bad: set[str] = set()
    for i, (western, arabic, eastern) in enumerate(
        zip(
            charset.WESTERN_DIGITS,
            charset.ARABIC_INDIC_DIGITS,
            charset.EASTERN_ARABIC_INDIC_DIGITS,
            strict=True,
        )
    ):
        pairs = [(western, arabic), (western, eastern)]
        if i in (4, 5, 6):
            pairs.append((arabic, eastern))
        for a, b in pairs:
            if a in covered and b in covered:
                ia, ib = _shaped(font_path, "ب " + a), _shaped(font_path, "ب " + b)
                if ia.shape == ib.shape and np.array_equal(ia, ib):
                    bad |= {a, b}
    return bad


def missing_symbols(font_path: Path) -> str:
    """Charset symbols this font can't draw correctly (as one string)."""
    face = freetype.Face(str(font_path))
    covered = {chr(code) for code, _ in face.get_chars()}
    bad = lookalike_digits(font_path, covered)
    return "".join(s for s in charset.SYMBOLS if s != " " and (s not in covered or s in bad))


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def download_family(repo: str, commit: str, entry: dict, allowed: set[str]) -> dict:
    family_dir = entry["dir"]
    folder, meta_text = find_metadata(repo, commit, family_dir)
    meta = parse_metadata(meta_text)

    if meta["license"] not in allowed:
        raise ValueError(f"license {meta['license']} is not allowed")
    if "arabic" not in meta["subsets"]:
        raise ValueError(f"does not list Arabic support (subsets: {meta['subsets']})")

    out_dir = FONTS_DIR / family_dir
    out_dir.mkdir(parents=True, exist_ok=True)
    base = f"https://raw.githubusercontent.com/{repo}/{commit}/{folder}/{family_dir}"

    license_file = LICENSE_FILES[meta["license"]]
    license_path = out_dir / license_file
    if not license_path.exists():
        license_path.write_bytes(fetch(f"{base}/{license_file}"))

    files = []
    for f in meta["files"]:
        path = out_dir / f["filename"]
        if not path.exists():
            # Brackets in variable-font names (e.g. Cairo[slnt,wght].ttf) must be URL-encoded.
            path.write_bytes(fetch(f"{base}/{urllib.request.quote(f['filename'])}"))
        files.append({**f, "sha256": sha256(path), "missing": missing_symbols(path)})

    return {
        "family": meta["family"],
        "dir": family_dir,
        "style": entry["style"],
        "role": entry["role"],
        "weight": entry.get("weight", 1.0),
        "license": meta["license"],
        "designer": meta["designer"],
        "source": f"https://github.com/{repo}/tree/{commit}/{folder}/{family_dir}",
        "license_file": f"data/fonts/{family_dir}/{license_file}",
        "files": files,
    }


def write_licenses_table(families: list[dict]) -> None:
    rows = [
        "| Font family | Source | License | Allowed for shipped models? |",
        "|---|---|---|---|",
    ]
    for fam in families:
        rows.append(
            f"| {fam['family']} | [{fam['dir']}]({fam['source']}) "
            f"| {LICENSE_NAMES[fam['license']]} | Yes (fonts are not shipped) |"
        )
    table = "\n".join([TABLE_START, *rows, TABLE_END])

    text = LICENSES_MD.read_text(encoding="utf-8")
    if TABLE_START in text:
        before = text.split(TABLE_START)[0]
        after = text.split(TABLE_END)[1]
        text = before + table + after
    else:
        text = text.rstrip() + "\n\n## Fonts\n\n" + table + "\n"
    LICENSES_MD.write_text(text, encoding="utf-8")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument(
        "--only",
        help="comma-separated font dirs to download (e.g. for CI); "
        "does not rewrite fonts.json or LICENSES.md",
    )
    parser.add_argument(
        "--update",
        action="store_true",
        help="re-resolve source_ref instead of reusing the commit pinned in fonts.json",
    )
    args = parser.parse_args(argv)

    config = yaml.safe_load(CONFIG.read_text(encoding="utf-8"))
    repo = config["source_repo"]
    allowed = set(config["allowed_licenses"])
    if MANIFEST.exists() and not args.update:
        commit = json.loads(MANIFEST.read_text(encoding="utf-8"))["source_commit"]
    else:
        commit = resolve_commit(repo, config["source_ref"])
    print(f"Google Fonts commit: {commit}")

    entries = config["fonts"]
    if args.only:
        wanted = set(args.only.split(","))
        entries = [e for e in entries if e["dir"] in wanted]
        if unknown := wanted - {e["dir"] for e in entries}:
            print(f"not in fonts.yaml: {', '.join(sorted(unknown))}")
            return 1

    families, failures = [], []
    for entry in entries:
        try:
            fam = download_family(repo, commit, entry, allowed)
        except Exception as err:  # report every failing family, then continue
            failures.append((entry["dir"], str(err)))
            print(f"  FAIL {entry['dir']}: {err}")
            continue
        families.append(fam)
        print(f"  ok   {fam['family']} ({len(fam['files'])} files, {fam['license']})")

    if args.only:
        return 1 if failures else 0

    manifest = {"source_repo": repo, "source_commit": commit, "families": families}
    MANIFEST.write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    write_licenses_table(families)

    n_files = sum(len(f["files"]) for f in families)
    print(f"\n{len(families)} families, {n_files} font files -> {FONTS_DIR}")
    print(f"Manifest: {MANIFEST}")
    if failures:
        print(f"{len(failures)} families failed: {', '.join(d for d, _ in failures)}")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
