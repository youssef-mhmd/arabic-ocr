"""Local HTTP API.

    arabic-ocr serve                     # http://127.0.0.1:8000 (this computer only)
    arabic-ocr serve --port 9000

    curl -F "file=@page.png" http://127.0.0.1:8000/ocr
    curl -F "file=@scan.pdf" "http://127.0.0.1:8000/ocr?format=pdf" -o searchable.pdf

Endpoints:
- GET  /health   -> {"status": "ok", "version": ...}
- POST /ocr      -> upload one image or PDF as the multipart field "file".
  Query options: format=json (default) | txt | hocr | alto | pdf, diacritics=true,
  tatweel=true, digits=keep|western|arabic, dpi=300.
- GET  /docs     -> interactive documentation (generated by FastAPI)

The server binds to 127.0.0.1 by default, so only this computer can reach it.
Everything runs offline: uploads are written to a temporary file, read, and
deleted.
"""

from __future__ import annotations

import os
import tempfile
from pathlib import Path
from typing import Annotated, Literal

from fastapi import FastAPI, File, HTTPException, Query, UploadFile
from fastapi.responses import FileResponse, PlainTextResponse, Response
from starlette.background import BackgroundTask

from arabic_ocr import __version__
from arabic_ocr.inputs import SUPPORTED

#: Uploads larger than this are refused (bytes).
MAX_UPLOAD = 200 * 1024 * 1024

MEDIA = {
    "json": "application/json",
    "txt": "text/plain; charset=utf-8",
    "hocr": "text/html; charset=utf-8",
    "alto": "application/xml",
}


def create_app(ocr=None) -> FastAPI:
    """The FastAPI app. `ocr`: an OCR instance (loaded on first request if None)."""
    app = FastAPI(
        title="arabic-ocr",
        version=__version__,
        description="Offline OCR for Arabic-script text (local API).",
    )
    state = {"ocr": ocr}

    def get_ocr():
        if state["ocr"] is None:
            from arabic_ocr.pipeline import OCR

            state["ocr"] = OCR()
        return state["ocr"]

    @app.get("/health")
    def health() -> dict:
        return {"status": "ok", "version": __version__}

    @app.post("/ocr")
    def ocr_endpoint(
        file: Annotated[
            UploadFile, File(description="An image (PNG, JPEG, TIFF, BMP, WebP) or PDF")
        ],
        format: Annotated[Literal["json", "txt", "hocr", "alto", "pdf"], Query()] = "json",
        diacritics: Annotated[bool, Query(description="Keep tashkeel")] = True,
        tatweel: Annotated[bool, Query(description="Keep tatweel (ـ)")] = True,
        digits: Annotated[Literal["keep", "western", "arabic"], Query()] = "keep",
        dpi: Annotated[int, Query(ge=50, le=600, description="Resolution for PDF pages")] = 300,
    ):
        suffix = Path(file.filename or "").suffix.lower()
        if suffix not in SUPPORTED:
            raise HTTPException(415, f"Unsupported file type '{suffix}'. Use: {sorted(SUPPORTED)}")
        data = file.file.read(MAX_UPLOAD + 1)
        if len(data) > MAX_UPLOAD:
            raise HTTPException(413, f"File larger than {MAX_UPLOAD // 2**20} MB")
        options = {"diacritics": diacritics, "tatweel": tatweel, "digits": digits}

        tmp = Path(tempfile.mkdtemp(prefix="arabic-ocr-"))
        src = tmp / f"upload{suffix}"
        src.write_bytes(data)

        def cleanup() -> None:
            for p in tmp.iterdir():
                p.unlink(missing_ok=True)
            tmp.rmdir()

        try:
            if format == "pdf":
                out = tmp / "searchable.pdf"
                get_ocr().to_pdf(src, out, dpi=dpi, **options)
                name = Path(file.filename).stem + ".pdf"
                return FileResponse(
                    out, media_type="application/pdf", filename=name,
                    background=BackgroundTask(cleanup),
                )  # fmt: skip
            doc = get_ocr().read(src, dpi=dpi, **options)
            doc.source = file.filename
        except ValueError as e:
            cleanup()
            raise HTTPException(422, str(e)) from e
        except Exception:
            cleanup()
            raise
        cleanup()
        if format == "txt":
            return PlainTextResponse(doc.text)
        body = {"json": doc.to_json, "hocr": doc.to_hocr, "alto": doc.to_alto}[format]()
        return Response(body, media_type=MEDIA[format])

    return app


def serve(host: str = "127.0.0.1", port: int = 8000) -> None:
    """Run the API server (blocks until stopped with Ctrl+C)."""
    import uvicorn

    if host not in ("127.0.0.1", "localhost", "::1"):
        print(
            f"Warning: listening on {host}: other computers on the network can use this server.",
            flush=True,
        )
    print(f"arabic-ocr {__version__} API on http://{host}:{port}  (docs: /docs)", flush=True)
    uvicorn.run(create_app(), host=host, port=port, log_level="info")


if __name__ == "__main__":
    serve(port=int(os.environ.get("PORT", 8000)))
